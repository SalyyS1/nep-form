import test from 'node:test';
import assert from 'node:assert/strict';
import { setup, register, address, cart, adminLogin, expectedQuote } from './test-helpers.mjs';

test('checkout prices, idempotency, racing stock and cancellation commit atomically', async t => {
  const api = await setup(t);
  const alice = api.client(), bob = api.client();
  await register(alice, 'alice@example.test');
  await register(bob, 'bob@example.test');
  await alice('/api/cart', 'POST', cart(2));
  await bob('/api/cart', 'POST', cart(2));
  const payload = { address, paymentMethod: 'cod', idempotencyKey: 'order-a', total: 1, note: '', expectedQuote: await expectedQuote(alice) };
  const results = await Promise.all([alice('/api/orders', 'POST', payload), bob('/api/orders', 'POST', { ...payload, idempotencyKey: 'order-b' })]);
  assert.deepEqual(results.map(result => result.status).sort(), [200, 409]);
  const winner = results[0].status === 200 ? alice : bob;
  const loser = winner === alice ? bob : alice;
  const order = results.find(result => result.status === 200).data.order;
  assert.equal(order.subtotal, 500000);
  assert.equal(order.total, 530000);
  assert.equal(order.paymentStatus, 'unpaid');
  assert.equal((await loser(`/api/orders/${order.id}`)).status, 404);
  assert.equal((await loser('/api/bootstrap')).data.cart.length, 1);
  const usedPayload = winner === alice ? payload : { ...payload, idempotencyKey: 'order-b' };
  const replay = await winner('/api/orders', 'POST', usedPayload);
  assert.equal(replay.data.order.id, order.id);
  assert.equal((await winner('/api/orders', 'POST', { ...usedPayload, note: 'Changed' })).status, 409);
  assert.equal((await winner('/api/bootstrap')).data.products[0].stock, 1);
  assert.equal((await winner('/api/orders/' + order.id + '/cancel', 'POST')).status, 200);
  await winner('/api/orders/' + order.id + '/cancel', 'POST');
  assert.equal((await winner('/api/bootstrap')).data.products[0].stock, 3);
  await api.restart();
  assert.equal((await winner('/api/bootstrap')).data.products[0].stock, 3);
});

test('bank stays pending, admin transitions and payment aggregates use persisted state', async t => {
  const api = await setup(t);
  const customer = api.client(), admin = api.client();
  await register(customer, 'customer@example.test');
  await adminLogin(admin);
  await admin('/api/admin/settings', 'PATCH', { bankEnabled: true, shippingFee: 12000 });
  await customer('/api/cart', 'POST', cart(1));
  const result = await customer('/api/orders', 'POST', { address, paymentMethod: 'bank', idempotencyKey: 'bank-one', expectedQuote: await expectedQuote(customer) });
  assert.equal(result.status, 200);
  const order = result.data.order;
  assert.equal(order.paymentStatus, 'pending');
  assert.equal((await admin('/api/admin')).data.stats.revenue, 0);
  assert.equal((await admin(`/api/admin/orders/${order.id}`, 'PATCH', { status: 'delivered' })).status, 409);
  assert.equal((await admin(`/api/admin/orders/${order.id}`, 'PATCH', { status: 'confirmed' })).status, 200);
  assert.equal((await customer(`/api/orders/${order.id}/cancel`, 'POST')).status, 409);
  await admin(`/api/admin/orders/${order.id}`, 'PATCH', { paymentStatus: 'paid' });
  const report = (await admin('/api/admin')).data;
  assert.equal(report.stats.revenue, 262000);
  assert.equal(report.stats.orderCount, 1);
  assert.equal(report.stats.pendingCount, 0);
  assert.equal(report.stats.lowStockCount, 1);
  assert.ok(report.audit.length >= 3);
  assert.ok(report.users.every(user => !('passwordHash' in user)));
  await admin(`/api/admin/orders/${order.id}`, 'PATCH', { status: 'cancelled' });
  await admin(`/api/admin/orders/${order.id}`, 'PATCH', { status: 'cancelled' });
  const cancelled = (await customer(`/api/orders/${order.id}`)).data.order;
  assert.equal(cancelled.paymentStatus, 'review');
  assert.equal((await customer('/api/bootstrap')).data.products[0].stock, 3);
  assert.equal((await admin('/api/admin')).data.stats.revenue, 0);
});

test('failed merge and invalid checkout preserve cart, addresses and inventory', async t => {
  const api = await setup(t);
  const request = api.client();
  await register(request, 'test@example.test');
  assert.equal((await request('/api/cart/merge', 'POST', { items: [cart(1), cart(5)] })).status, 409);
  assert.equal((await request('/api/cart/merge', 'POST', { items: [null] })).status, 400);
  assert.deepEqual((await request('/api/bootstrap')).data.cart, []);
  await request('/api/cart', 'POST', cart(1));
  assert.equal((await request('/api/orders', 'POST', { address: { ...address, recipient: '' }, saveAddress: true, paymentMethod: 'cod', idempotencyKey: 'invalid', expectedQuote: await expectedQuote(request) })).status, 400);
  const after = (await request('/api/bootstrap')).data;
  assert.equal(after.products[0].stock, 3);
  assert.equal(after.cart.length, 1);
  assert.deepEqual(after.addresses, []);
  assert.deepEqual(after.orders, []);
});

import test from 'node:test';
import assert from 'node:assert/strict';
import { setup, adminLogin, register, address, cart, expectedQuote } from './test-helpers.mjs';

test('stale full product editor cannot resurrect stock consumed by checkout or cancellation', async t => {
  const api = await setup(t);
  const admin = api.client(), customer = api.client();
  await adminLogin(admin);
  await register(customer, 'customer@example.test');
  const snapshot = (await admin('/api/admin')).data.products[0];
  assert.equal(snapshot.version, 1);
  await customer('/api/cart', 'POST', cart(2));
  const checkout = await customer('/api/orders', 'POST', { address, paymentMethod: 'cod', idempotencyKey: 'version-order', expectedQuote: await expectedQuote(customer) });
  assert.equal(checkout.status, 200);
  const stale = await admin('/api/admin/products/shirt', 'PATCH', { ...snapshot, name: 'Old editor', expectedVersion: snapshot.version });
  assert.equal(stale.status, 409);
  assert.equal(stale.data.code, 'PRODUCT_VERSION_CONFLICT');
  let current = (await admin('/api/admin')).data.products[0];
  assert.equal(current.stock, 1);
  assert.equal(current.version, 2);
  assert.equal(current.name, snapshot.name);
  assert.equal((await admin('/api/admin/products/shirt', 'PATCH', { name: 'No version' })).status, 400);
  await customer(`/api/orders/${checkout.data.order.id}/cancel`, 'POST');
  assert.equal((await admin('/api/admin/products/shirt', 'PATCH', { ...current, expectedVersion: current.version })).status, 409);
  current = (await admin('/api/admin')).data.products[0];
  assert.equal(current.stock, 3);
  assert.equal(current.version, 3);
  assert.equal((await admin('/api/admin/products/shirt', 'PATCH', { name: 'Fresh editor', expectedVersion: current.version })).status, 200);
  assert.equal((await admin('/api/admin')).data.products[0].version, 4);
});

test('checkout rejects changed price and shipping quotes without side effects, then accepts reconfirmation', async t => {
  const api = await setup(t);
  const admin = api.client(), customer = api.client();
  await adminLogin(admin);
  await register(customer, 'customer@example.test');
  await customer('/api/cart', 'POST', cart(1));
  assert.equal((await customer('/api/orders', 'POST', { address, paymentMethod: 'cod', idempotencyKey: 'missing-quote' })).status, 400);
  const payload = { address, saveAddress: true, paymentMethod: 'cod', idempotencyKey: 'requote', expectedQuote: await expectedQuote(customer) };
  await admin('/api/admin/products/shirt', 'PATCH', { price: 300000, expectedVersion: 1 });
  let result = await customer('/api/orders', 'POST', payload);
  assert.equal(result.status, 409);
  assert.equal(result.data.code, 'CART_CHANGED');
  let state = (await customer('/api/bootstrap')).data;
  assert.equal(state.products[0].stock, 3);
  assert.equal(state.products[0].version, 2);
  assert.equal(state.cart.length, 1);
  assert.deepEqual(state.orders, []);
  assert.deepEqual(state.addresses, []);
  payload.expectedQuote = await expectedQuote(customer);
  await admin('/api/admin/settings', 'PATCH', { shippingFee: 50000 });
  result = await customer('/api/orders', 'POST', payload);
  assert.equal(result.status, 409);
  assert.equal(result.data.code, 'CART_CHANGED');
  state = (await customer('/api/bootstrap')).data;
  assert.equal(state.cart.length, 1);
  assert.deepEqual(state.orders, []);
  assert.deepEqual(state.addresses, []);
  payload.expectedQuote = await expectedQuote(customer);
  result = await customer('/api/orders', 'POST', payload);
  assert.equal(result.status, 200);
  assert.equal(result.data.order.total, 350000);
  // A valid replay keeps its original quote even after settings and cart changed.
  await admin('/api/admin/settings', 'PATCH', { shippingFee: 90000 });
  const replay = await customer('/api/orders', 'POST', payload);
  assert.equal(replay.status, 200);
  assert.equal(replay.data.order.id, result.data.order.id);
  assert.equal(replay.data.order.total, 350000);
  assert.equal((await customer('/api/orders', 'POST', { ...payload, expectedQuote: { ...payload.expectedQuote, total: 1 } })).data.code, 'IDEMPOTENCY_CONFLICT');
});
